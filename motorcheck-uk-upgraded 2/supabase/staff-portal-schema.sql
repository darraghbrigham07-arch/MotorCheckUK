-- MotorCheck UK staff portal shared data schema.
-- Run in Supabase SQL Editor. Access is mediated by the server-side staff API.
create table if not exists public.staff_tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  owner text not null default 'Unassigned',
  status text not null default 'Open' check (status in ('Open','In progress','Done')),
  priority text not null default 'Normal' check (priority in ('Low','Normal','High','Urgent')),
  due_date date,
  created_at timestamptz not null default now()
);
create table if not exists public.staff_enquiries (
  id bigint generated by default as identity primary key,
  customer_name text not null default '', email text not null default '', registration text not null default '',
  subject text not null default '', message text not null default '',
  status text not null default 'New' check (status in ('New','In progress','Waiting for customer','Resolved','Closed')),
  assigned_to text not null default 'Unassigned', priority text not null default 'Normal' check (priority in ('Low','Normal','High','Urgent')),
  created_at timestamptz not null default now()
);
create table if not exists public.staff_directory (
  id bigint generated by default as identity primary key,
  full_name text not null, email text not null unique, phone text not null default '',
  role text not null default 'Staff' check (role in ('Admin','Manager','Staff','Support')),
  active boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists public.staff_jobs (
  id bigint generated by default as identity primary key,
  title text not null, description text not null default '', category text not null default 'General',
  status text not null default 'Open' check (status in ('Open','In progress','Blocked','Done')),
  priority text not null default 'Normal' check (priority in ('Low','Normal','High','Urgent')),
  assigned_to text not null default 'Unassigned', due_date date, created_at timestamptz not null default now()
);
-- Keep direct browser access closed. Server API uses the service-role key and checks the staff session.
alter table public.staff_tasks enable row level security;
alter table public.staff_enquiries enable row level security;
alter table public.staff_directory enable row level security;
alter table public.staff_jobs enable row level security;
revoke all on public.staff_tasks from anon, authenticated;
revoke all on public.staff_enquiries from anon, authenticated;
revoke all on public.staff_directory from anon, authenticated;
revoke all on public.staff_jobs from anon, authenticated;
